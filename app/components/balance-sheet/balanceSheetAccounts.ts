export const BALANCE_SHEET_ACCOUNTS: BalanceSheetAccount[] = ROWS.map(
  ([code, category, subcategory, name]) => ({
    code,
    category,
    subcategory,
    name,
    isHeader: / – Header$/.test(name),
  }),
);

/** Current Assets are codes 1010–1499 (1000 is their header). */
export function isCurrentAssetCode(code: string): boolean {
  const n = Number(code);
  return n > 1000 && n < 1500;
}

export const CURRENT_ASSET_ACCOUNTS = BALANCE_SHEET_ACCOUNTS.filter(
  (a) => !a.isHeader && isCurrentAssetCode(a.code),
);
